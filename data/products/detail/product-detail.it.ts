export function getItalianHardTubeFittingContent(detail: {
  slug: string;
  model: string;
  specs?: { label?: string; value?: unknown }[];
  specifications?: { label?: string; value?: unknown }[];
}) {
  if (!italianHardTubeFittingSlugs.includes(detail.slug)) return;
  if (detail.slug === italianHardTubeSampleSlug) return italianHardTubeSample;
  if (isHardTubePlug(detail)) {
    const plug = getHardTubePlugPresentation(detail, "it");
    return {
      ...italianHardTubeSample,
      title: plug.name,
      description: plug.description,
      imageAlt: plug.model + ", " + plug.name.toLowerCase() + " in " + plug.material + " · " + plug.color.toLowerCase(),
      faqs: plug.copy.faq.map(([question, answer]) => ({ question, answer })),
    };
  }

  const specs = detail.specs ?? detail.specifications ?? [];
  const pressure = specs.find(spec => spec.label === "额定压力" || spec.label === "耐压")?.value;
  if (typeof pressure === "string") {
    const value = (label: string) => String(specs.find(spec => spec.label === label)?.value ?? "");
    return italianHighPressureFitting(detail.model, value("螺纹规格"), value("主体材质"), value("接管外径"), value("流道内径"), pressure);
  }
  const od = specs.find(spec => spec.label === "接管外径")?.value;
  const thread = specs.find(spec => spec.label === "螺纹规格")?.value;
  if (typeof od !== "string" || typeof thread !== "string") return;
  const model = detail.model;
  const material = specs.find(spec => spec.label === "主体材质")?.value;
  if (typeof material !== "string") return;
  const compact = /^(?:HF6|HFL6|HN6|HNF6)-/.test(model);
  const ferrule = /^(?:HN|HN6|HNF|HNF6)-/.test(model);
  const title = ferrule
    ? (compact ? "Raccordo compatto a ogiva" : "Raccordo zigrinato a ogiva in formato standard")
    : (compact ? "Raccordo compatto a fondo piatto" : italianHardTubeSample.title);
  const sealing = ferrule ? "L'ogiva realizza la tenuta." : "La tenuta sul fondo si ottiene con una guarnizione flangiata.";
  return {
    ...italianHardTubeSample,
    title,
    description: model + " è un " + title.toLowerCase() + " per tubi rigidi di diametro esterno " + od + ". Ha una filettatura " + thread + " e un corpo in " + material + ". " + sealing + " Il raccordo collega tubi rigidi in circuiti microfluidici, apparecchiature IVD, strumenti analitici e sistemi di automazione di laboratorio.",
    imageAlt: model + ", " + title.toLowerCase() + " in " + material,
    faqs: italianHardTubeSample.faqs.map(faq => ({
      question: faq.question.replace("HFL-M6-16-PV-N", model).replace("PVDF", material)
        .replace("raccordo standard zigrinato a fondo piatto", title.toLowerCase()),
      answer: faq.answer.replace("1.6 mm", od).replace("M6×1", thread).replace("del PVDF", "del " + material),
    })),
  };
}

function italianHighPressureFitting(model: string, thread: string, material: string, od: string, bore: string, pressure: string) {
  const titles: Readonly<Record<string, string>> = {
    PNC: "Raccordo ad alta pressione in formato standard",
    PNC6: "Raccordo compatto ad alta pressione",
    PNF: "Kit di raccordo a ogiva ad alta pressione",
    PU: "Raccordo diritto ad alta pressione con filettature femmina",
    PUT: "Raccordo a T ad alta pressione con filettature femmina",
  };
  const title = titles[model.split("-")[0]];
  if (!title || !thread || !material || (!od && !bore)) return;
  const materialName = material === "SUS" ? "acciaio inossidabile SUS" : material;
  const id = bore.replace(/（ID）$/, "");
  const description = id
    ? model + " è un raccordo ad alta pressione in acciaio inossidabile con pressione nominale di " + pressure + ", filettatura " + thread + " e passaggio di diametro interno " + id + ". È destinato ai collegamenti nei circuiti microfluidici ad alta pressione, negli strumenti analitici, nelle apparecchiature IVD e nei sistemi di automazione di laboratorio."
    : model + " è un raccordo ad alta pressione per tubi rigidi di diametro esterno " + od + ". Ha una filettatura " + thread + ", un corpo in " + materialName + " e una pressione nominale di " + pressure + ". È destinato ai collegamenti di tubi rigidi ad alta pressione negli strumenti analitici e nei sistemi di automazione di laboratorio.";
  const faqs = id ? [
    { question: "Qual è la pressione nominale di " + model + "?", answer: "La pressione nominale di " + model + " è " + pressure + ". Nelle condizioni di esercizio, verificate il margine di sicurezza in base a fluido, temperatura, disposizione dei tubi e variazioni di pressione." },
    { question: "Quale filettatura usa " + model + "?", answer: model + " usa la filettatura " + thread + ". Prima del montaggio, verificate che filettatura e geometria di tenuta corrispondano a quelle dell'attacco dell'apparecchiatura." },
    { question: "Qual è il diametro interno del passaggio di " + model + "?", answer: "Il diametro interno del passaggio di " + model + " è " + id + ". Influisce sulla perdita di carico, sulla velocità del fluido e sul volume morto del circuito." },
    { question: "Come si verifica la compatibilità del fluido con l'acciaio inossidabile?", answer: "Valutate la compatibilità dell'acciaio inossidabile in base a tipo di fluido, concentrazione, temperatura di esercizio, tempo di contatto e metodo di pulizia." },
    { question: "Posso richiedere un disegno 2D di " + model + "?", answer: "Sì. Aggiungete il modello alla lista e selezionate la richiesta del disegno. Il nostro team tecnico verificherà la versione applicabile." },
  ] : italianHardTubeSample.faqs.map(faq => ({
    question: faq.question.replace("HFL-M6-16-PV-N", model).replace("il PVDF", material === "SUS" ? "l'acciaio inossidabile SUS" : "il " + material)
      .replace("raccordo standard zigrinato a fondo piatto", "raccordo ad alta pressione"),
    answer: faq.answer.replace("1.6 mm", od).replace("M6×1", thread)
      .replace("del PVDF", material === "SUS" ? "dell'acciaio inossidabile SUS" : "del " + material),
  }));
  return { ...italianHardTubeSample, title, description, imageAlt: model + ", " + title.toLowerCase() + " in " + materialName, faqs };
}

