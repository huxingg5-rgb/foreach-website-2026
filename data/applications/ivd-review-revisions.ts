/** Apply after hierarchy assembly so the full task copy is not replaced by summaries. */
export function applyIvdReviewRevision(kind: EnglishApplicationKind, document: ApplicationDocument): ApplicationDocument {
  if (kind !== 'ivd') return document;
  const revision = revisions[document.slug];
  if (!revision) return document;
  if (document.sections.length !== revision.sections.length || revision.sections.some((section, index) => section.id !== document.sections[index].id)) {
    throw new Error(`IVD review section structure changed: ${document.slug || 'hub'}`);
  }
  return {
    ...document,
    ...revision,
    sections: revision.sections.map((section, index) => {
      const links = new Map<string, ApplicationLink>();
      for (const block of [...section.blocks, ...document.sections[index].blocks]) {
        if (block.type === 'links') for (const link of block.items) {
          if (!links.has(link.href)) links.set(link.href, link);
        }
      }
      return {
        ...section,
        blocks: [
          ...section.blocks.filter(block => block.type !== 'links'),
          ...(links.size ? [{ type: 'links' as const, items: [...links.values()] }] : []),
        ],
      };
    }),
  };
}
