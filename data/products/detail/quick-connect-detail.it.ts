const reviewedSlugs = new Set(italianQuickConnectFittingSlugs);
const selectedModels = new Map(quickConnectFittingSelectionProducts.map(row => [row.model, row]));

export function withItalianQuickConnectConnection<T extends { slug: string } & Record<string, unknown>>(data: T): T {
  if (!data.slug.startsWith("q4005-") || !reviewedSlugs.has(data.slug)) return data;
  const identity = selectedModels.get(data.slug.toUpperCase());
  if (identity?.tubeCode !== "05" || identity.tubeOrThread !== "7.9 mm") return data;
  const updateItems = (items: unknown) => Array.isArray(items) ? items.map(item => {
    // Some legacy detail records misclassify this tubing size code as a thread.
    return item?.label === "螺纹规格" && item.value === identity.tubeCode
      ? { ...item, label: "接管内径", value: identity.tubeOrThread } : item;
  }) : items;
  return {
    ...data,
    specs: updateItems(data.specs),
    specifications: updateItems(data.specifications),
    specGroups: Array.isArray(data.specGroups) ? data.specGroups.map(group => ({ ...group, items: updateItems(group.items) })) : data.specGroups,
  };
}

export function getItalianQuickConnectFittingContent(slug: string): GermanProductDetailContent | undefined {
  if (!reviewedSlugs.has(slug) || !isPublishedFittingDetailRoute(fittingFamily, slug)) return;
  const model = slug.toUpperCase();
  const row = selectedModels.get(model);
  if (!row) return;
  const { series, housingMaterial: material, sealingRingMaterial: seal, tubeOrThread: size } = row;
  const threaded = !size.endsWith(" mm");
  const role = row.genderCode === "P" ? "attacco maschio" : "attacco femmina";
  const panel = row.panelCode === "M";
  const valved = row.valvedCode === "V";
  const style = (row.shapeCode === "S" ? "diritto" : "a gomito") + " " + series + " " + (valved ? "con valvola" : "senza valvola");
  const title = "Innesto rapido " + style + ", " + role;
  const connectionDescription = threaded ? " con collegamento filettato " + size : " per tubi di diametro interno " + size;
  const description = model + " è un " + role + " " + style + connectionDescription + ". Ha un corpo in " + material + " e tenute in " + seal + (panel ? " e si monta a pannello." : " e si monta in linea.") + " Consente di scollegare rapidamente il circuito fluidico dello strumento." + (valved ? " La valvola chiude il flusso su questo lato allo scollegamento." : "");
  return {
    title,
    description,
    imageAlt: model + " – " + title,
    faqs: [
      { question: "Quale collegamento usa " + model + "?", answer: (threaded ? "Usa un collegamento filettato " + size : "È adatto a tubi di diametro interno " + size) + ". Per la scelta, verificate anche l’attacco complementare, la configurazione della valvola e il montaggio." },
      { question: model + " è con valvola o senza valvola?", answer: (valved ? "Il modello ha una valvola di intercettazione." : "Il modello è senza valvola.") + " Un attacco con valvola chiude il proprio lato del circuito allo scollegamento. Un attacco senza valvola lascia quel lato aperto." },
      { question: "Questo " + role + " " + style + " si può montare a pannello?", answer: panel ? "Il modello è adatto al montaggio su pannelli, involucri o staffe fisse dello strumento." : "Il modello si monta in linea per il collegamento diretto dei tubi." },
      { question: "Il " + material + " è compatibile con il fluido?", answer: "Valutate insieme fluido, temperatura, pressione di esercizio, requisiti di pulizia e materiale della tenuta. In caso di dubbi, comunicate le condizioni al nostro team tecnico per una verifica." },
      { question: "Posso richiedere un disegno 2D di " + model + "?", answer: "Aggiungete il modello alla lista e richiedete il disegno. Il nostro team tecnico verificherà il codice articolo e la revisione prima di inviarlo." },
    ],
    bottomCta: {
      title: "Raccordi per ordini in quantità e applicazioni su misura",
      description: "FOREACH può assistervi nella scelta dei raccordi, nella fornitura in quantità e nella personalizzazione in base al tipo di attacco, alle dimensioni del tubo, ai materiali, alla tenuta, al montaggio e alle condizioni d'impiego.",
      buttonText: "Contattaci",
      href: "/en/contact/",
    },
  };
}
