import assert from "node:assert/strict";
import { defaultFlangedTubingChoice, describeFlangedEnd, describeFlangedEndFinish, flangedTubingSummary, normalizeFlangedChoice } from "../../data/products/configurator/flanged-tubing";
import { deleteFlangedConfiguration, emptyFlangedConfigurationStore, parseFlangedConfigurationStore, saveFlangedConfiguration } from "../../data/products/configurator/flanged-tubing-configurations";
import { buildFlangedDrawingSheets, getFlangedDrawingTemplate } from "../../components/products/tubing-assemblies/flanged-tubing-drawing";

const choice = { ...defaultFlangedTubingChoice(), length: "1500", tolerance: "5", labelA: true, textA: "<script>&试剂 A", notes: "工程确认要求" };
const first = saveFlangedConfiguration(emptyFlangedConfigurationStore(), choice, "配置 1", null, "2026-11-09T01:00:00Z", "test-1");
const restored = parseFlangedConfigurationStore(JSON.stringify(first.store));
assert.equal(restored.configurations[0].choice.textA, choice.textA);
assert.equal(restored.activeId, "test-1");
const edit = saveFlangedConfiguration(restored, { ...choice, length: "1600" }, "配置 1", "test-1", "2026-11-09T02:00:00Z");
assert.equal(edit.store.configurations.length, 1);
assert.equal(edit.record.revision, 2);
assert.equal(edit.record.id, first.record.id);
assert.equal(saveFlangedConfiguration(edit.store, edit.record.choice, edit.record.name, edit.record.id).record.revision, 2);
const copy = saveFlangedConfiguration(edit.store, edit.record.choice, "配置 2", null, "2026-11-09T03:00:00Z", "test-2");
assert.equal(copy.store.configurations.length, 2);
assert.equal(copy.store.nextNumber, 3);
assert.equal(copy.store.configurations[0].choice.length, "1600");
assert.equal(copy.record.revision, 1);
const beforeDelete = JSON.stringify(copy.store);
const removeInactive = deleteFlangedConfiguration(copy.store, "test-1", 2);
assert.deepEqual(removeInactive.configurations.map(record => record.id), ["test-2"]);
assert.equal(removeInactive.activeId, "test-2");
const removeActive = deleteFlangedConfiguration(copy.store, "test-2", 1);
assert.equal(removeActive.activeId, "test-1", "deleting the active record must select a remaining configuration");
assert.equal(removeActive.configurations[0].revision, 2);
const removeAll = deleteFlangedConfiguration(removeActive, "test-1", 2);
assert.equal(removeAll.activeId, null);
assert.equal(removeAll.nextNumber, 3, "deleted numbers must not be reused");
assert.equal(parseFlangedConfigurationStore(JSON.stringify(removeAll)).configurations.length, 0, "deletion must survive a storage roundtrip");
assert.equal(saveFlangedConfiguration(removeAll, choice, "新配置", null).record.number, 3);
assert.equal(deleteFlangedConfiguration(copy.store, "already-deleted", 1), copy.store);
assert.throws(() => deleteFlangedConfiguration(copy.store, "test-1", 1), /其他窗口更新/);
assert.throws(() => saveFlangedConfiguration(removeAll, choice, "已删除的配置", "test-1"), /已被删除/, "a stale editor must not resurrect a deleted configuration");
assert.equal(JSON.stringify(copy.store), beforeDelete, "deletion must not mutate the original snapshot");
assert.throws(() => parseFlangedConfigurationStore('{"version":1,"nextNumber":1,"configurations":[{}]}'));
assert.throws(() => saveFlangedConfiguration(copy.store, { ...choice, length: "0" }, "bad", null));
const sheets = buildFlangedDrawingSheets(edit.record);
assert.equal(sheets.length, 2);
assert.ok(sheets[0].includes("1600 ±5"));
assert.ok(sheets[0].includes("&lt;script&gt;&amp;试剂 A"));
assert.ok(sheets.join("").includes('data-source-model="HFL-U28-16-PV-N"'));
assert.ok(sheets.join("").includes('data-source-kind="original-pdf-vector"'));
assert.ok(!sheets.join("").includes('data-source-kind="raster-outline-trace"'));
assert.ok(sheets[1].includes("配置补充说明"));
assert.ok(sheets[0].includes('data-template-key="fl-double"'));
assert.ok(sheets[0].includes('data-bom-part="4"'));
assert.ok(sheets[0].includes('data-vector-drawing="true"'));
assert.ok(!/<image\b|<foreignObject\b|data:image|<canvas\b/.test(sheets.join("")));
const single = saveFlangedConfiguration(copy.store, { ...choice, mode: "single", freeEnd: "针", freeEndNote: "针配套规格" }, "单端", null);
const singleSheets = buildFlangedDrawingSheets(single.record).join("");
assert.ok(singleSheets.includes("B 端客户应用：针"));
assert.ok(singleSheets.includes("针配套规格"));
assert.ok(!singleSheets.includes("B 端接头"));
const plain = { ...defaultFlangedTubingChoice(), length: "500" };
const legacyMaterial = "旧版自由材质".repeat(5);
const flLegacy = { ...plain, a: { ...plain.a, series:"FL", fittingModel:undefined, accessoryCode:undefined, material: legacyMaterial }, b: { ...plain.b, series:"FL", fittingModel:undefined, accessoryCode:undefined, material: legacyMaterial } };
assert.equal(describeFlangedEndFinish(normalizeFlangedChoice(flLegacy).a), "PVDF · 本色");
assert.equal(describeFlangedEnd(normalizeFlangedChoice(flLegacy).a), "翻边 · HFL-U28-16-PV-N · PVDF · 本色");
assert.ok(!flangedTubingSummary(flLegacy).includes(legacyMaterial));
const legacyPages = buildFlangedDrawingSheets(saveFlangedConfiguration(emptyFlangedConfigurationStore(), flLegacy, "旧配置", null).record);
assert.equal(legacyPages.length, 1);
assert.ok(!legacyPages.join("").includes(legacyMaterial));
assert.ok(!legacyPages.join("").includes("材质待确认"));
assert.ok(!legacyPages.join("").includes("材质按需求"));
assert.ok(legacyPages[0].includes("材质：PVDF"), "HFL drawings label the real fitting material");
const mixedMaterial = { ...flLegacy, b: { ...plain.b, series: "FL6", fittingModel:undefined, accessoryCode:undefined, material: "PPS",color:"黑色" } };
assert.equal(describeFlangedEndFinish(normalizeFlangedChoice(mixedMaterial).b), "PPS · 黑色");
assert.ok(flangedTubingSummary(mixedMaterial).includes("HFL6-U28-16-PS-B · PPS · 黑色"));
const mixedMaterialPages = buildFlangedDrawingSheets(saveFlangedConfiguration(emptyFlangedConfigurationStore(), mixedMaterial, "混合配置", null).record).join("");
assert.ok(!mixedMaterialPages.includes(legacyMaterial));
assert.ok(mixedMaterialPages.includes("材质：PPS"));
assert.ok(mixedMaterialPages.includes('data-source-model="HFL6-U28-16-PS-B"'));
for (const mode of ["single", "double"] as const) for (const a of ["FL", "FL6"] as const) for (const b of ["FL", "FL6"] as const) {
  const sample = { ...plain, mode, a: { ...plain.a, series: a, fittingModel:undefined, accessoryCode:undefined, material:a === "FL6" ? "PPS" : "",color:a === "FL6" ? "黑色" : "本色" }, b: { ...plain.b, series: b, fittingModel:undefined, accessoryCode:undefined, material:b === "FL6" ? "PPS" : "",color:b === "FL6" ? "黑色" : "本色" } };
  const expected = mode === "single" ? a === "FL" ? "fl-single" : "fl6-single" : a !== b ? "mixed-double" : a === "FL" ? "fl-double" : "fl6-double";
  assert.equal(getFlangedDrawingTemplate(sample).key, expected);
  const result = saveFlangedConfiguration(emptyFlangedConfigurationStore(), sample, "配置", null);
  const pages = buildFlangedDrawingSheets(result.record);
  assert.equal(pages.length, 1);
  assert.ok(pages[0].includes('data-bom-part="5"'));
  assert.equal(pages[0].includes('data-bom-part="9"'), mode === "double");
  assert.ok(pages[0].includes(`data-source-series="H${a}"`));
  assert.equal((pages[0].match(/data-source-series=/g) || []).length, mode === "double" ? 2 : 1);
  assert.deepEqual([...pages[0].matchAll(/data-source-series="(HFL6?)"/g)].map(m => m[1]), mode === "double" ? [`H${a}`, `H${b}`] : [`H${a}`]);
  assert.equal(pages[0].includes('data-assembly-part="8"'), mode === "double");
  assert.ok(!/<image\b|href=|data:image/.test(pages.join("")));
}
for (const stopA of ["无", "O 型圈", "硅胶管"] as const) for (const stopB of ["无", "O 型圈", "硅胶管"] as const) {
  const selected = { ...plain, a: { ...plain.a, stop: stopA }, b: { ...plain.b, stop: stopB }, labelA: true, labelB: true, textA: "123", textB: "www" };
  const { record } = saveFlangedConfiguration(emptyFlangedConfigurationStore(), selected, "部件组合", null);
  const svg = buildFlangedDrawingSheets(record)[0];
  assert.equal(svg.includes('data-assembly-part="3"'), stopA !== "无");
  assert.equal(svg.includes('data-assembly-part="7"'), stopB !== "无");
  assert.ok(svg.includes('data-assembly-part="5"'));
  assert.ok(svg.includes('data-assembly-part="9"'));
  assert.ok(svg.includes('width="1140" height="14"'), "tube must remain continuous");
}
