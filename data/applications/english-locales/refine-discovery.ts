export function refineEnglishDiscovery(document: ApplicationDocument, kind: EnglishApplicationKind): ApplicationDocument {
  const title = titles[kind]?.[document.slug];
  const description = descriptions[kind]?.[document.slug];
  if (!title && !description) return document;
  return { ...document, ...(title ? { seoTitle: `${title} | FOREACH` } : {}), ...(description ? { description } : {}) };
}
