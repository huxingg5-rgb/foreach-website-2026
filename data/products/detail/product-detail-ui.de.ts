export function germanProductDetailText(text: string) {
  return Object.hasOwn(ui, text) ? ui[text] : text;
}

export function germanProductBreadcrumbLabel(label: string) {
  return Object.hasOwn(breadcrumbLabels, label) ? breadcrumbLabels[label] : germanProductDetailText(label);
}

function specKey(label: string) {
  return label.trim().replace(/[:：]$/, "").toLowerCase();
}

const hardTubeOuterDiameterLabels = new Set([
  "tube od", "tubing od", "tube outer diameter", "tubing outer diameter", "接管外径",
]);

export function germanProductSpecLabel(label: string, isHardTube = false, value?: unknown) {
  const key = specKey(label);
  if (isHardTube && hardTubeOuterDiameterLabels.has(key)) return "Leitungs-Außendurchmesser";
  if (key === "sealing method" && value === "Female Thread-to-Barb Adapter") return "Anschlussart";
  return Object.hasOwn(specLabels, key) ? specLabels[key] : label;
}

