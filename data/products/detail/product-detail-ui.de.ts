export function germanProductSpecValue<T>(label: string, value: T): string | T {
  const key = specKey(label);
  if (!Object.hasOwn(specCategories, key) || typeof value !== "string") return value;
  const copy = specCategories[key];
  const translatedValue = Object.hasOwn(copy, value)
    ? value
    : Object.keys(copy).find(option => option.toLowerCase() === value.toLowerCase());
  return translatedValue ? copy[translatedValue] : value;
}
