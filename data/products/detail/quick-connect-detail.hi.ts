const available = new Set(hindiQuickConnectFittingSlugs);
const models = new Map(quickConnectFittingSelectionProducts.map(row => [row.model, row]));

export function withHindiQuickConnectConnection<T extends { slug: string } & Record<string, unknown>>(data: T): T {
  if (!data.slug.startsWith("q4005-") || !available.has(data.slug)) return data;
  const row = models.get(data.slug.toUpperCase());
  if (row?.tubeCode !== "05" || row.tubeOrThread !== "7.9 mm") return data;
  const localizeSizeRow = (items: unknown) => Array.isArray(items) ? items.map(item =>
    item?.label === "螺纹规格" && item.value === row.tubeCode
      ? { ...item, label: "接管内径", value: row.tubeOrThread }
      : item
  ) : items;
  return {
    ...data,
    specs: localizeSizeRow(data.specs),
    specifications: localizeSizeRow(data.specifications),
    specGroups: Array.isArray(data.specGroups) ? data.specGroups.map(group => ({ ...group, items: localizeSizeRow(group.items) })) : data.specGroups,
  };
}


