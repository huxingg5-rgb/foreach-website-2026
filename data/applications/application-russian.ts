function translateRussianSource(source: string): string {
  const normalizedSource = source.replace(/[。；]\s*$/u, "");
  const exact =
    NAVIGATION_RU_EXACT[source] ??
    NAVIGATION_RU_EXACT[normalizedSource] ??
    ivdRuExactText[source] ??
    ivdRuExactText[normalizedSource] ??
    APPLICATION_RU_TERMS[source] ??
    APPLICATION_RU_TERMS[normalizedSource] ??
    ivdRuTermText[source];
  if (exact) return exact;

  if (source.includes(" / ")) {
    return source
      .split(" / ")
      .map((part) => translateRussianSource(part.trim()))
      .join(" / ");
  }

  let translated = source;
  const replacements = [
    ...Object.entries(APPLICATION_RU_TERMS),
    ...Object.entries(ivdRuTermText),
    ...APPLICATION_RU_REPLACEMENTS,
    ...ivdRuReplacements,
  ].sort((a, b) => b[0].length - a[0].length);

  for (const [from, to] of replacements) translated = translated.replaceAll(from, to);

  if (/[\u3400-\u9fff]/u.test(translated)) return fallbackRussianCopy(source);

  return translated
    .replaceAll("、", ", ")
    .replaceAll("，", ", ")
    .replaceAll("；", "; ")
    .replaceAll("：", ": ")
    .replaceAll("。", ". ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[.;]\s*$/, "");
}

export function translateRussianNavigationText(source: string) {
  return NAVIGATION_RU_EXACT[source] ?? translateRussianSource(source);
}

export function createRussianExactText(
  sourceExactText: Record<string, string>,
  overrides: RussianApplicationExactText = {},
): RussianApplicationExactText {
  return Object.fromEntries(
    Object.keys(sourceExactText).map((source) => [
      source,
      overrides[source] ?? translateRussianSource(source),
    ]),
  );
}

function translateRussianText(value: string, exactText: RussianApplicationExactText) {
  if (value.startsWith("/")) return localizeRussianHref(value);
  return exactText[value] ?? translateRussianSource(value);
}

export function translateRussianApplicationData<T>(
  source: T,
  exactText: RussianApplicationExactText,
): T {
  if (typeof source === "string") return translateRussianText(source, exactText) as T;
  if (Array.isArray(source)) {
    return source.map((item) => translateRussianApplicationData(item, exactText)) as T;
  }
  if (source && typeof source === "object") {
    return Object.fromEntries(
      Object.entries(source).map(([key, value]) => [
        key,
        translateRussianApplicationData(value, exactText),
      ]),
    ) as T;
  }
  return source;
}
