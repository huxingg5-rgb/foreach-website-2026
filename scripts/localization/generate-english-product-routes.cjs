/* eslint-disable @typescript-eslint/no-require-imports -- This generator intentionally uses CommonJS. */

const fs = require("node:fs");
const path = require("node:path");

const root = process.cwd();
const sourceRoot = path.join(root, "out", "products");
const outputPath = path.join(
  root,
  "data",
  "products",
  "product-detail-routes.generated.ts"
);

if (!fs.existsSync(sourceRoot)) {
  throw new Error(
    "Missing out/products. Run npm run build before generating English product routes."
  );
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : [fullPath];
  });
}

const routes = walk(sourceRoot)
  .filter((filePath) => path.basename(filePath) === "index.html")
  .map((filePath) => path.relative(sourceRoot, path.dirname(filePath)))
  .filter((relativePath) => relativePath && relativePath !== ".")
  .map((relativePath) => relativePath.split(path.sep).filter(Boolean))
  .sort((left, right) => left.join("/").localeCompare(right.join("/")));

const output = `/* =========================================================
   product-detail-routes.generated.ts

   Generated by:
   node scripts/localization/generate-english-product-routes.cjs

   Source:
   Static Chinese product routes emitted to out/products by npm run build.

   Do not edit manually. The segment values and URL slugs are preserved.
========================================================= */

export const englishProductDetailRoutes = ${JSON.stringify(routes, null, 2)} as const;
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, "utf8");

console.log(`Generated ${routes.length} English product route records.`);
console.log(outputPath);
