function correctSyringeSpecifications(value: unknown, isHmd6: boolean): unknown {
  if (Array.isArray(value)) return value.map(item => correctSyringeSpecifications(item, isHmd6));
  if (!value || typeof value !== "object") return value;
  const row = value as Record<string, unknown>;
  // HMD6 channel range confirmed by the user for the Chinese product pages.
  if (isHmd6 && row.label === "通道数") {
    return {...row, value: "1–8 通道可选"};
  }
  if (row.label === "液量精确度（额定行程）" && row.value === "≤0.05%（250 μL 及以上注射器）；≤1%（100 μL 及以下注射器）") {
    return {...row, label: "液量重复性（额定行程）", value: "重复性误差 ≤0.05%（250 μL 及以上注射器）；≤0.1%（100 μL 及以下注射器）"};
  }
  return Object.fromEntries(Object.entries(row).map(([key, item]) => [key, correctSyringeSpecifications(item, isHmd6)]));
}

